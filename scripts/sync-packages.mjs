// Copies the built data into each language package, in the form that language can bundle.
//   node scripts/sync-packages.mjs   (run by `npm run build`)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const ROOT = new URL("../", import.meta.url).pathname;
const FILES = ["worldref.json", "subdivisions.json"];
const TARGETS = {
    python: "python/worldref/data/",
    swift: "Sources/WorldRef/Resources/",
    kotlin: "kotlin/src/main/resources/worldref/",
    go: "go/data/",
    csharp: "csharp/WorldRef/Data/",
};
for (const dir of Object.values(TARGETS)) {
    mkdirSync(`${ROOT}${dir}`, { recursive: true });
    for (const f of FILES) copyFileSync(`${ROOT}data/${f}`, `${ROOT}${dir}${f}`);
}

// Dart: no file assets outside Flutter, so the JSON ships as string constants.
const dart = FILES.map((f) => {
    const json = readFileSync(`${ROOT}data/${f}`, "utf8");
    if (json.includes("'''")) throw new Error(`${f} contains ''' and cannot be a Dart raw string`);
    const name = f === "worldref.json" ? "countriesJson" : "subdivisionsJson";
    return `const String ${name} = r'''${json}''';\n`;
});
const dartOut = `${ROOT}dart/lib/src/data.g.dart`;
mkdirSync(dirname(dartOut), { recursive: true });
writeFileSync(dartOut, `// GENERATED by scripts/sync-packages.mjs from data/. Do not edit.\n// ignore_for_file: lines_longer_than_80_chars\n\n${dart.join("\n")}`);

console.log(`synced ${FILES.join(", ")} into ${Object.keys(TARGETS).join(", ")}, dart`);
