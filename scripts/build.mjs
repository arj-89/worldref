function capital(iso) {
    const pol = E.POLICY[iso];
    if (pol?.capital_ar) return { ar: pol.capital_ar, en: pol.capital_en, src: "editorial" };
    const caps = wd[iso].capitals ?? [];
    if (E.CAPITAL_CHOICE[iso]) {
        const c = caps.find((x) => x.en === E.CAPITAL_CHOICE[iso].en);
        override(iso, "capital", E.CAPITAL_CHOICE[iso].en, E.CAPITAL_CHOICE[iso].why);
        return { ar: c?.ar ?? null, en: E.CAPITAL_CHOICE[iso].en, src: "wikidata" };
    }
    if (caps.length) return { ar: caps.find((c) => c.ar)?.ar ?? null, en: caps.find((c) => c.en)?.en ?? null, src: "wikidata" };
    if (E.CAPITAL_FILL[iso]) {
        override(iso, "capital", E.CAPITAL_FILL[iso].en, E.CAPITAL_FILL[iso].why);
        return { ar: E.CAPITAL_FILL[iso].ar, en: E.CAPITAL_FILL[iso].en, src: "wikidata" };
    }
    return { ar: null, en: null, src: null };
}
const wbKey = (iso) => (iso === "XK" ? "XKX" : codeMappings[iso]?._alpha3);
function population(iso) {
    const w = wb.population[wbKey(iso)];
    if (w) return { value: Math.round(w.value), year: w.year, src: "worldbank" };
    const p = (wd[iso].population ?? []).filter((x) => x.date).sort((a, b) => b.date.localeCompare(a.date))[0] ?? first(wd[iso].population);
    return p ? { value: p.value, year: p.date ? Number(p.date.slice(0, 4)) : null, src: "wikidata" } : { value: null, year: null, src: null };
}
function area(iso) {
    const w = wb.area_km2[wbKey(iso)];
    if (w) return { value: Math.round(w.value), src: "worldbank" };
    const m2 = first(wd[iso].area_m2);
    return m2 ? { value: Math.round(m2 / 1e6), src: "wikidata" } : { value: null, src: null };
}

