// ---------- currency ----------
function currencies(iso) {
    const pol = E.POLICY[iso];
    const codes = pol?.currencies ?? (currencyData[iso] ?? []).map((e) => Object.entries(e)[0]).filter(([, v]) => !v._to && v._tender !== "false").map(([c]) => c);
    return uniq(codes).map((code) => {
        const fixed = pol?.currency_names?.[code];
        if (fixed) override(iso, `currency.${code}.name`, fixed, "Policy: no excluded-state name in currency names");
        const ar = curNames.ar[code] ?? {};
        const en = curNames.en[code] ?? {};
        const newSign = ar["symbol-alt-variant"] && /[⃀-⃏]/.test(ar["symbol-alt-variant"]) ? ar["symbol-alt-variant"] : null;
        return {
            code,
            name_ar: fixed?.ar ?? ar.displayName ?? null,
            name_en: fixed?.en ?? en.displayName ?? null,
            symbol: newSign ?? en["symbol-alt-narrow"] ?? en.symbol ?? null,
            symbol_ar: (ar.symbol ?? "").replace(/‏/g, "") || null,
            symbol_fallback: newSign ? (ar.symbol ?? "").replace(/‏/g, "").replace(/\.$/, "") : null,
        };
    });
}

