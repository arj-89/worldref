const feminine = (m) => m.split(" ").map((w) => (w.endsWith("ي") ? `${w}ة` : w)).join(" ");
function nationality(iso, kind) {
    const has = kind === "country" || E.NATIONALITY_TERRITORIES.includes(iso);
    if (!has) return { nationality_ar_m: null, nationality_ar_f: null, nationality_en: null };
    let ar = null;
    const cands = uniq((wd[iso].demonym_ar ?? []).map((s) => s.replace(/[\u064B-\u065F\u0670]/g, "").trim())).filter((s) => s.endsWith("ي") && !/(ين|ون|ات|ان)$/.test(s));
    if (E.NATIONALITY_AR[iso]) {
        ar = E.NATIONALITY_AR[iso];
        override(iso, "nationality_ar_m", ar, cands.length ? `Standard Arabic form; Wikidata's "${cands[0]}" is wrong` : "Standard Arabic form; Wikidata has none");
    } else if (cands.length) ar = cands.sort((a, b) => a.length - b.length)[0];
    let en = null;
    if (E.NATIONALITY_EN[iso]) {
        en = E.NATIONALITY_EN[iso];
        override(iso, "nationality_en", en, "Factbook form is not a single adjective");
    } else {
        const g = (wd[iso].fips ?? []).find((f) => fb[f]);
        const adj = g ? fb[g].nationality_adjective : null;
        if (adj && !/^none/i.test(adj)) en = adj.split(/ or |, |;|\//)[0].replace(/\(.*?\)/g, "").trim() || null;
        if (!en) en = (wd[iso].demonym_en ?? []).find((d) => !/s$/.test(d) || d.endsWith("ss")) ?? null;
    }
    return { nationality_ar_m: ar, nationality_ar_f: ar ? feminine(ar) : null, nationality_en: en };
}

