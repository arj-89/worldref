const block = (body, tag) => body.match(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`))?.[1] ?? null;
const pattern = (b) => (b ? block(b, "nationalNumberPattern")?.replace(/\s+/g, "") ?? null : null);
const lengthsOf = (b) => {
    const pl = b?.match(/<possibleLengths national="([^"]*)"/)?.[1];
    if (!pl || pl === "-1") return [];
    return pl.split(",").flatMap((part) => {
        const r = part.match(/\[(\d+)-(\d+)\]/);
        if (!r) return [Number(part)];
        const out = [];
        for (let n = Number(r[1]); n <= Number(r[2]); n++) out.push(n);
        return out;
    });
};
const TYPES = ["fixedLine", "mobile", "tollFree", "premiumRate", "sharedCost", "personalNumber", "voip", "pager", "uan", "voicemail"];
const formatsOf = (t) => {
    let body = t.body;
    if (!/<availableFormats>/.test(body)) {
        const main = Object.values(territories).find((x) => x.attr.countryCode === t.attr.countryCode && x.attr.mainCountryForCode === "true");
        if (main) body = main.body;
    }
    return [...(block(body, "availableFormats") ?? "").matchAll(/<numberFormat pattern="([^"]+)"[^>]*>([\s\S]*?)<\/numberFormat>/g)].map((f) => {
        const lds = [...f[2].matchAll(/<leadingDigits>([\s\S]*?)<\/leadingDigits>/g)].map((x) => x[1].replace(/\s+/g, ""));
        const intl = f[2].match(/<intlFormat>(.*?)<\/intlFormat>/)?.[1];
        return { pattern: f[1], leading: lds.at(-1) ?? null, format: intl && intl !== "NA" ? intl : f[2].match(/<format>(.*?)<\/format>/)[1] };
    });
};
function displayMask(t, example) {
    if (!example) return null;
    for (const f of formatsOf(t)) {
        if (f.leading && !new RegExp(`^(?:${f.leading})`).test(example)) continue;
        const re = new RegExp(`^(?:${f.pattern})$`);
        if (!re.test(example)) continue;
        return example.replace(re, f.format).replace(/\d/g, "#");
    }
    return null;
}
const codeCount = {};
for (const t of Object.values(territories)) codeCount[t.attr.countryCode] = (codeCount[t.attr.countryCode] ?? 0) + 1;
function phoneEntry(t) {
    const mobile = block(t.body, "mobile");
    const fixed = block(t.body, "fixedLine");
    const mobilePattern = pattern(mobile);
    const lengths = uniq(TYPES.flatMap((ty) => lengthsOf(block(t.body, ty)))).sort((a, b) => a - b);
    const example = mobile ? block(mobile, "exampleNumber") : null;
    return {
        calling_code: `+${t.attr.countryCode}`,
        leading_digits: t.attr.leadingDigits?.replace(/\s+/g, "") ?? null,
        primary: t.attr.mainCountryForCode === "true" || codeCount[t.attr.countryCode] === 1,
        trunk_prefix: t.attr.nationalPrefix ?? null,
        pattern: pattern(block(t.body, "generalDesc")),
        lengths,
        mobile_pattern: mobilePattern,
        mobile_lengths: lengthsOf(mobile),
        mobile_prefixes: mobilePattern ? leadingPrefixes(mobilePattern) : [],
        mobile_distinguishable: !(mobilePattern && pattern(fixed) === mobilePattern),
        mobile_example: example,
        mobile_format: displayMask(t, example),
    };
}
