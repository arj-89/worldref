function names(iso) {
    const pol = E.POLICY[iso];
    const pick = (lang) => {
        if (pol?.[`name_${lang}`]) return pol[`name_${lang}`];
        if (lang === "ar" && E.SHORT_NAMES[iso]?.ar) {
            override(iso, "name_ar", E.SHORT_NAMES[iso].ar, E.SHORT_NAMES[iso].why);
            return E.SHORT_NAMES[iso].ar;
        }
        const t = terr[lang];
        let n = t[`${iso}-alt-short`] ?? t[iso];
        if (lang === "en") n = n.replace(/ & /g, " and ").replace(/\bSt\. /g, "Saint ");
        if (AWKWARD.test(n)) {
            const variant = t[`${iso}-alt-variant`];
            if (variant && !AWKWARD.test(variant)) n = variant;
            else if (first(wd[iso][`label_${lang}`])) n = first(wd[iso][`label_${lang}`]);
        }
        return n;
    };
    return { ar: pick("ar"), en: pick("en") };
}

function officialName(iso, lang, short) {
    const pol = E.POLICY[iso]?.[`official_name_${lang}`];
    if (pol) return pol;
    if (lang === "en") {
        const g = (wd[iso].fips ?? []).find((f) => fb[f]);
        const long = g ? fb[g].long_name : null;
        if (long && !/^none/i.test(long)) return long.split(";")[0].trim();
    }
    const c = (wd[iso][`official_${lang}`] ?? []).filter((s) => !TASHKEEL.test(s) && s !== short);
    return c.sort((a, b) => b.length - a.length)[0] ?? null;
}

function aliases(iso, lang, name) {
    const block = new Set(E.ALIAS_BLOCK[iso] ?? []);
    const seen = new Set([normalize(name)]);
    const out = [];
    const t = terr[lang];
    const pool = [t[iso], t[`${iso}-alt-short`], t[`${iso}-alt-variant`], ...(E.ALIAS_ADD[iso]?.[lang] ?? []), ...(wd[iso][`label_${lang}`] ?? []), ...(wd[iso][`alias_${lang}`] ?? [])];
    for (const a of pool) {
        if (!a || block.has(a) || a.length > 60 || [iso, codeMappings[iso]?._alpha3].includes(a) || /israel|إسرائيل|اسرائيل/i.test(a)) continue;
        const k = normalize(a);
        if (seen.has(k)) continue;
        seen.add(k);
        out.push(a);
    }
    return out.slice(0, 12);
}

