/** Looks up a description by schema path, ignoring the `_ar`/`_en` suffix in single-language builds. */
export function describe(path) {
    if (!path) return null;
    const clean = path.replace(/\[\]/g, "[]");
    return FIELDS[clean] ?? FIELDS[clean.replace(/(^|\.)(\w+?)(_[mf])?$/, (m, dot, k, g) => `${dot}${k}_ar${g ?? ""}`)] ?? FIELDS[clean.replace(/(\w+)$/, "$1_en")] ?? null;
}
